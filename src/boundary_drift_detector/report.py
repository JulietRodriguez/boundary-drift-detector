"""Drift report as JSON and Markdown."""

from __future__ import annotations

import json

from boundary_drift_detector import __version__
from boundary_drift_detector.compare import KINDS, DriftReport

KIND_LABELS = {
    "undeclared": "Undeclared (exists, not in the boundary)",
    "missing": "Missing (declared, not found)",
    "region": "Region drift",
    "encryption": "Encryption drift",
    "public": "Public exposure drift",
    "unverified": "Unverified expectations",
}


def to_dict(r: DriftReport, *, as_of: str) -> dict:
    return {
        "tool": {"name": "boundary-drift-detector", "version": __version__},
        "as_of": as_of,
        "boundary": {
            "name": r.boundary.name,
            "source": r.boundary.source,
            "declared_resources": r.declared_count,
            "allowed_regions": sorted(r.allowed_regions),
            "allowed_accounts": sorted(r.allowed_accounts),
        },
        "inventory": {
            "sources": r.actual_sources,
            "resources_in_scope": r.actual_count,
            "ignored_by_type": dict(sorted(r.ignored.items())),
        },
        "matched": len(r.matches),
        "match_methods": {m: sum(1 for *_, how in r.matches if how == m) for m in ("arn", "id", "name")},
        "drift_by_kind": r.counts(),
        "drift_by_severity": r.severity_counts(),
        "drifts": [d.to_dict() for d in r.drifts],
        "notes": r.notes,
    }


def to_json(r: DriftReport, *, as_of: str) -> str:
    return json.dumps(to_dict(r, as_of=as_of), indent=2, ensure_ascii=False) + "\n"


def _esc(v: object) -> str:
    return str(v if v is not None else "-").replace("|", "\\|").replace("\n", " ")


def to_markdown(r: DriftReport, *, as_of: str) -> str:
    out: list[str] = []
    w = out.append
    sev = r.severity_counts()
    w(f"# Boundary drift report: {_esc(r.boundary.name)}")
    w("")
    w(f"As of {as_of}. Declared boundary from `{_esc(r.boundary.source)}`; inventory from "
      f"{', '.join(f'`{_esc(s)}`' for s in r.actual_sources) or 'live AWS Config'}.")  # fmt: skip
    w("")
    total = len([d for d in r.drifts if d.kind != "unverified"])
    w(f"## Result: {total} drift finding(s)" + (" — boundary matches the inventory" if total == 0 else ""))
    w("")
    w("| Critical | High | Medium | Low | Info |")
    w("|---:|---:|---:|---:|---:|")
    w(f"| {sev['critical']} | {sev['high']} | {sev['medium']} | {sev['low']} | {sev['info']} |")
    w("")
    w(f"- Declared resources: {r.declared_count}")
    w(f"- Resources in the inventory (in scope): {r.actual_count}")
    if r.ignored:
        w(
            "- Ignored inventory types (not system assets): "
            + ", ".join(f"{t} ({n})" for t, n in sorted(r.ignored.items()))
        )
    w(f"- Matched: {len(r.matches)}")
    if r.allowed_regions:
        w(f"- Boundary regions: {', '.join(sorted(r.allowed_regions))}")
    if r.allowed_accounts:
        w(f"- Boundary accounts: {', '.join(sorted(r.allowed_accounts))}")
    for note in r.notes:
        w(f"- {_esc(note)}")
    w("")
    for kind in KINDS:
        items = [d for d in r.drifts if d.kind == kind]
        if not items:
            continue
        w(f"## {KIND_LABELS[kind]} ({len(items)})")
        w("")
        w("| Severity | Type | Resource | Region | Control | Detail |")
        w("|---|---|---|---|---|---|")
        for d in items:
            res = d.resource
            ident = res.arn or res.id
            w(
                f"| {d.severity.value} | {_esc(res.type)} | `{_esc(ident)}` | {_esc(res.region)} | "
                f"{d.control.upper() or '-'} | {_esc(d.message)} |"
            )
        w("")
    w("## What to do")
    w("")
    w("- **Undeclared:** add the resource to the SSP inventory (and assess it), or remove it.")
    w("- **Missing:** confirm it was decommissioned and update the SSP, or find out why the inventory lacks it.")
    w("- **Region / encryption / public:** fix the resource, or update the SSP and get the change approved")
    w("  through configuration management. Boundary changes may need the AO's review.")
    w("")
    w(f"Generated by boundary-drift-detector {__version__}.")
    w("")
    return "\n".join(out)
